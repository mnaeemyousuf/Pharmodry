'use client';

import * as React from 'react';
import Link from 'next/link';
import { useQuery, useQueryClient } from '@tanstack/react-query';
import { CheckCheck } from 'lucide-react';
import { toast } from 'sonner';
import { NotificationEvent } from '@pharmodry/types';
import { humanize } from '@pharmodry/ui';
import { api } from '@/lib/api';
import { cn, fmtDateTime } from '@/lib/utils';
import { Button, Checkbox } from '@/components/ui/primitives';
import { PageHeader, Section } from '@/components/page';
import { SeverityDot } from '@/components/status-badge';

interface N {
  id: string;
  title: string;
  body: string;
  severity: 'INFO' | 'WARNING' | 'CRITICAL';
  event: string;
  link?: string;
  readAt?: string | null;
  createdAt: string;
}
interface Pref {
  event: string;
  inApp: boolean;
  email: boolean;
}

export default function NotificationsPage() {
  const qc = useQueryClient();
  const { data } = useQuery({ queryKey: ['notifications'], queryFn: () => api.page<N>('/notifications') });
  const { data: prefs } = useQuery({ queryKey: ['notification-prefs'], queryFn: () => api.get<Pref[]>('/notifications/preferences') });
  const pref = (e: string) => prefs?.find((p) => p.event === e) ?? { event: e, inApp: true, email: false };
  const setPref = async (e: string, patch: Partial<Pref>) => {
    const p = { ...pref(e), ...patch };
    await api.put('/notifications/preferences', p);
    qc.invalidateQueries({ queryKey: ['notification-prefs'] });
    toast.success('Preference saved');
  };
  return (
    <>
      <PageHeader
        title="Notifications"
        description="Alerts generated by workflows and scheduled compliance scans (expiry, low stock, overdue CAPAs/deviations, calibration, QA backlog)."
        actions={
          <Button
            variant="outline"
            onClick={async () => {
              await api.post('/notifications/read', {});
              qc.invalidateQueries({ queryKey: ['notifications'] });
            }}
          >
            <CheckCheck /> Mark all read
          </Button>
        }
      />
      <div className="grid gap-4 xl:grid-cols-[1.6fr_1fr]">
        <Section title="Inbox">
          <ul className="divide-y">
            {data?.data.map((n) => (
              <li key={n.id} className={cn('flex gap-3 py-3', !n.readAt && 'font-medium')}>
                <span className="mt-1.5">
                  <SeverityDot severity={n.severity} />
                </span>
                <div className="min-w-0 flex-1">
                  {n.link ? (
                    <Link className="text-[13.5px] text-primary hover:underline" href={n.link}>
                      {n.title}
                    </Link>
                  ) : (
                    <div className="text-[13.5px]">{n.title}</div>
                  )}
                  <div className="text-[12.5px] font-normal text-muted-foreground">{n.body}</div>
                </div>
                <div className="whitespace-nowrap text-xs font-normal text-muted-foreground">{fmtDateTime(n.createdAt)}</div>
              </li>
            ))}
          </ul>
        </Section>
        <Section title="My preferences" description="In-app delivery is on by default. The email channel is architecture-ready; delivery requires SMTP configuration by an administrator.">
          <table className="w-full text-[13px]">
            <thead>
              <tr className="border-b text-left text-xs text-muted-foreground">
                <th className="py-2">Event</th>
                <th className="py-2 text-center">In-app</th>
                <th className="py-2 text-center">Email</th>
              </tr>
            </thead>
            <tbody>
              {Object.values(NotificationEvent).map((e) => (
                <tr key={e} className="border-b last:border-0">
                  <td className="py-2">{humanize(e)}</td>
                  <td className="py-2 text-center">
                    <Checkbox checked={pref(e).inApp} onCheckedChange={(v) => setPref(e, { inApp: !!v })} aria-label={`${e} in-app`} />
                  </td>
                  <td className="py-2 text-center">
                    <Checkbox checked={pref(e).email} onCheckedChange={(v) => setPref(e, { email: !!v })} aria-label={`${e} email`} />
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </Section>
      </div>
    </>
  );
}
