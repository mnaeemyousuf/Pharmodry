'use client';

import * as React from 'react';
import { useRouter } from 'next/navigation';
import { useQuery } from '@tanstack/react-query';
import { toast } from 'sonner';
import type { BlockingReason } from '@pharmodry/types';
import { api, ApiError, errorMessage } from '@/lib/api';
import { useAuth } from '@/lib/auth';
import { useProducts } from '@/lib/hooks';
import { fmtNum, toIsoDate } from '@/lib/utils';
import type { Availability, Plan } from '@/lib/types';
import { Button, Input, Select } from '@/components/ui/primitives';
import { Blockers, Field, PageHeader, Section } from '@/components/page';
import { StatusBadge } from '@/components/status-badge';

export default function NewBatchPage() {
  const router = useRouter();
  const { user } = useAuth();
  const { data: products } = useProducts();
  const [f, setF] = React.useState({ siteId: user?.sites[0]?.id ?? '', productId: '', planLineId: '', plannedQuantity: '', plannedStart: toIsoDate(new Date(Date.now() + 86_400_000)) });
  const [busy, setBusy] = React.useState(false);
  const [reasons, setReasons] = React.useState<BlockingReason[]>([]);
  const product = products?.find((p) => p.id === f.productId);
  const { data: plans } = useQuery({ queryKey: ['plans-approved'], queryFn: () => api.page<Plan>('/production-plans', { status: 'APPROVED', pageSize: 50 }).then((r) => r.data) });
  const planLines = (plans ?? []).flatMap((p) => p.lines.filter((l) => l.productId === f.productId).map((l) => ({ ...l, plan: p })));
  const qty = Number(f.plannedQuantity || product?.standardBatchSize || 0);
  const { data: avail } = useQuery({
    queryKey: ['availability', f.productId, f.siteId, qty],
    queryFn: () => api.get<Availability>('/production-plans/availability', { productId: f.productId, siteId: f.siteId, quantity: qty }),
    enabled: !!f.productId && qty > 0,
  });
  const submit = async (e: React.FormEvent) => {
    e.preventDefault();
    setBusy(true);
    setReasons([]);
    try {
      const b = await api.post<{ id: string; batchNumber: string }>('/batches', {
        siteId: f.siteId,
        productId: f.productId,
        planLineId: f.planLineId || undefined,
        plannedQuantity: f.plannedQuantity ? Number(f.plannedQuantity) : undefined,
        plannedStart: new Date(f.plannedStart).toISOString(),
      });
      toast.success(`Batch ${b.batchNumber} created`);
      router.push(`/production/batches/${b.id}`);
    } catch (e2) {
      if (e2 instanceof ApiError && e2.reasons.length) setReasons(e2.reasons);
      toast.error(errorMessage(e2));
    } finally {
      setBusy(false);
    }
  };
  return (
    <>
      <PageHeader title="New batch" crumbs={[{ label: 'Batches', href: '/production/batches' }, { label: 'New' }]} description="The batch number is generated by the configured rule (e.g. PCM-2026-000123). The eBMR is copied from the product’s active manufacturing template." />
      <form onSubmit={submit} className="space-y-4">
        <Section title="Batch">
          <div className="grid gap-4 md:grid-cols-3">
            <Field label="Site" required>
              <Select value={f.siteId} onChange={(e) => setF({ ...f, siteId: e.target.value })}>
                {user?.sites.map((s) => (
                  <option key={s.id} value={s.id}>
                    {s.name}
                  </option>
                ))}
              </Select>
            </Field>
            <Field label="Product" required>
              <Select value={f.productId} onChange={(e) => setF({ ...f, productId: e.target.value, planLineId: '' })} required data-testid="batch-product">
                <option value="">Select…</option>
                {products?.filter((p) => p.status === 'ACTIVE').map((p) => (
                  <option key={p.id} value={p.id}>
                    {p.code} — {p.genericName} {p.strength}
                  </option>
                ))}
              </Select>
            </Field>
            <Field label="Production plan line" hint="Links the batch to plan achievement">
              <Select value={f.planLineId} onChange={(e) => setF({ ...f, planLineId: e.target.value })}>
                <option value="">Unplanned</option>
                {planLines.map((l) => (
                  <option key={l.id} value={l.id}>
                    {l.plan.number} — {l.plannedBatches} batch(es)
                  </option>
                ))}
              </Select>
            </Field>
            <Field label="Batch size" hint={product ? `Standard: ${fmtNum(product.standardBatchSize)}` : undefined}>
              <Input type="number" min={1} placeholder={product ? String(product.standardBatchSize) : ''} value={f.plannedQuantity} onChange={(e) => setF({ ...f, plannedQuantity: e.target.value })} />
            </Field>
            <Field label="Planned start" required>
              <Input type="date" value={f.plannedStart} onChange={(e) => setF({ ...f, plannedStart: e.target.value })} required />
            </Field>
          </div>
        </Section>
        {avail && (
          <Section title="Material availability" description="Released, unexpired stock net of existing reservations. Quarantined stock cannot be reserved.">
            <div className="mb-2">{avail.feasible ? <StatusBadge status="PASS" label="All materials available" /> : <StatusBadge status="FAIL" label="Shortage — reservation will be blocked" />}</div>
            <table className="w-full text-[13px]">
              <thead>
                <tr className="border-b text-left text-xs text-muted-foreground">
                  <th className="py-1.5">Material</th>
                  <th className="py-1.5 text-right">Required</th>
                  <th className="py-1.5 text-right">Available</th>
                  <th className="py-1.5 text-right">Shortage</th>
                </tr>
              </thead>
              <tbody>
                {avail.lines.map((l) => (
                  <tr key={l.materialId} className="border-b last:border-0">
                    <td className="py-1.5">
                      {l.code} <span className="text-muted-foreground">{l.name}</span>
                    </td>
                    <td className="py-1.5 text-right tabular">{fmtNum(l.required)}</td>
                    <td className="py-1.5 text-right tabular">{fmtNum(l.available)}</td>
                    <td className={l.shortage > 0 ? 'py-1.5 text-right font-semibold text-danger tabular' : 'py-1.5 text-right tabular'}>{l.shortage > 0 ? fmtNum(l.shortage) : '—'}</td>
                  </tr>
                ))}
              </tbody>
            </table>
          </Section>
        )}
        {reasons.length > 0 && <Blockers reasons={reasons} title="Batch cannot be created" />}
        <div className="flex justify-end gap-2">
          <Button type="button" variant="outline" onClick={() => router.back()}>
            Cancel
          </Button>
          <Button type="submit" loading={busy} data-testid="batch-submit">
            Create batch
          </Button>
        </div>
      </form>
    </>
  );
}
